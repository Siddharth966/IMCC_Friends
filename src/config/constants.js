// Helper function to get friend by slug
export const getFriendBySlug = (slug) => {
  return friends.find(friend => friend.slug === slug);
};

// Get all categories
export const getAllCategories = () => {
  const categories = new Set();
  friends.forEach(friend => {
    friend.categories?.forEach(cat => categories.add(cat));
  });
  return Array.from(categories);
};

// Get all tags
export const getAllTags = () => {
  const tags = new Set();
  friends.forEach(friend => {
    friend.tags?.forEach(tag => tags.add(tag));
  });
  return Array.from(tags);
};

// Get online friends
export const getOnlineFriends = () => {
  return friends.filter(friend => friend.isOnline);
};

// Get special friends
export const getSpecialFriends = () => {
  return friends.filter(friend => friend.isSpecial);
};

// Search friends by name or description
export const searchFriends = (query) => {
  const searchTerm = query.toLowerCase();
  return friends.filter(friend => 
    friend.title.toLowerCase().includes(searchTerm) ||
    friend.description.toLowerCase().includes(searchTerm) ||
    friend.fullName.toLowerCase().includes(searchTerm) ||
    friend.nickname.toLowerCase().includes(searchTerm)
  );
};

// Get friends by category
export const getFriendsByCategory = (category) => {
  return friends.filter(friend => 
    friend.categories?.includes(category)
  );
};

// Get random friend (for featured section)
export const getRandomFriend = () => {
  return friends[Math.floor(Math.random() * friends.length)];
};

// Get friend statistics
export const getFriendStats = () => {
  return {
    totalFriends: friends.length,
    onlineFriends: friends.filter(f => f.isOnline).length,
    specialFriends: friends.filter(f => f.isSpecial).length,
    averageRating: (friends.reduce((sum, f) => sum + f.rating, 0) / friends.length).toFixed(1),
    totalMessages: friends.reduce((sum, f) => sum + f.messages, 0)
  };
};